/// SMS認証（AUT-02・AUT-03）を何のために行うか
/// 認証コードの送信・確認の流れは共通で、確認できたときの処理だけが異なる
enum PhoneVerificationPurpose {
  /// ログイン／サインアップ（機能仕様書4.1.1）
  /// 確認できたらサインインする
  signIn,
  /// ログイン中のUserの再認証（AUT-04「パスコードを忘れた場合」）
  /// 確認できたら、呼び出し元がパスコードを解除する
  reauthentication,
  /// ログイン中のUserの電話番号の変更（SET-01）
  /// 確認できたら新しい番号に差し替える（uidは変わらない）
  phoneNumberChange,
}
