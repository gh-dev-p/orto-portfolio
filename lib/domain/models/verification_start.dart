/// SMS認証コードの送信・再送の結果
enum VerificationStart {
  /// SMSを送信した（AUT-03へ進む）
  codeSent,
  /// 端末の自動検証で、コード入力なしに目的の処理（サインイン・再認証・電話番号の差し替え）まで完了した
  verified,
  /// 送信に失敗した（理由は各画面のViewModelがエラー種別として持つ）
  failed,
}
