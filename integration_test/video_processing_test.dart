// iOSとAndroidのネイティブの動画処理（VideoProcessingChannel）が、同じ入出力になることを実機相当で確かめる。
// 実行：flutter test integration_test/video_processing_test.dart --flavor dev -d <device>
// iOSでは、ios/Flutter/Debug-dev.xcconfigのFLUTTER_TARGETが起動ファイルを固定するため、実行の間だけその行を外す
// （外さないと通常のアプリが起動し、テストが始まらない）。
void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  late Directory dir;
  late File input;
  final service = VideoProcessingService();

  setUpAll(() async {
    dir = await Directory.systemTemp.createTemp('video_processing_test');
    input = File('${dir.path}/input.mp4');
    await input.writeAsBytes(base64Decode(_sampleVideo));
  });

  tearDownAll(() => dir.delete(recursive: true));

  testWidgets('回転を反映した大きさと長さを読める', (tester) async {
    final info = await service.probe(input);
    expect(info.width, 1080);
    expect(info.height, 1920);
    expect(info.durationMs, inInclusiveRange(1900, 2100));
  });

  testWidgets('短辺720pxに圧縮し、進み具合を知らせる', (tester) async {
    final output = File('${dir.path}/output.mp4');
    final progress = <double>[];
    final info = await service.compress(input, output, onProgress: progress.add);
    expect(info.width, AlbumLimits.videoMaxShortSide);
    expect(info.height, 1280);
    expect(info.durationMs, inInclusiveRange(1800, 2200));
    expect(info.sizeBytes, await output.length());
    expect(info.sizeBytes, greaterThan(0));
    // 2秒の動画を約2Mbpsに抑えた大きさ（映像＋音声の目安の1.5倍まで）。
    expect(info.sizeBytes, lessThan(800 * 1024));

    // 圧縮した動画はもう一度読める（回転が映像に焼き込まれ、向きは変わらない）。
    final reread = await service.probe(output);
    expect(reread.width, 720);
    expect(reread.height, 1280);
    expect(progress, isNotEmpty);
  });

  testWidgets('短辺が上限以下の動画は拡大しない', (tester) async {
    final first = File('${dir.path}/first.mp4');
    final second = File('${dir.path}/second.mp4');
    await service.compress(input, first);
    final info = await service.compress(first, second);
    expect(info.width, 720);
    expect(info.height, 1280);
  });

  testWidgets('サムネイルをJPEGで作る', (tester) async {
    final output = File('${dir.path}/thumb.jpg');
    await service.thumbnail(input, output);
    final Uint8List bytes = await output.readAsBytes();
    expect(bytes.sublist(0, 2), [0xFF, 0xD8]);
    final size = await readImageSize(output);
    expect(size.height, AlbumLimits.thumbnailMaxSide);
    expect(size.width, inInclusiveRange(268, 272));
  });

  testWidgets('動画でないファイルはinvalidInputになる', (tester) async {
    final text = File('${dir.path}/text.mp4');
    await text.writeAsString('not a video');
    await expectLater(
      service.probe(text),
      throwsA(isA<VideoProcessingException>().having((e) => e.error, 'error', VideoProcessingError.invalidInput)),
    );
    await expectLater(
      service.compress(text, File('${dir.path}/never.mp4')),
      throwsA(isA<VideoProcessingException>().having((e) => e.error, 'error', VideoProcessingError.invalidInput)),
    );
  });
}

